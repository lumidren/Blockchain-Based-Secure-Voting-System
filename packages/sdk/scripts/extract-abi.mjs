// Extracts ABIs (and bytecode for local deployments) from the Foundry build into typed `as const` modules.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../../..");
const out = resolve(root, "packages/sdk/src/abi");
mkdirSync(out, { recursive: true });
const contracts = [
  ["Election", "Election.sol"],
  ["VeriVoteFactory", "VeriVoteFactory.sol"],
  ["VoterRegistry", "VoterRegistry.sol"],
  ["TrusteeCoordinator", "TrusteeCoordinator.sol"],
  ["Tally", "Tally.sol"],
];
const index = [];
for (const [name, file] of contracts) {
  const art = JSON.parse(readFileSync(resolve(root, "contracts/out", file, `${name}.json`), "utf8"));
  const camel = name.charAt(0).toLowerCase() + name.slice(1);
  writeFileSync(resolve(out, `${camel}.ts`), `// GENERATED by scripts/extract-abi.mjs from contracts/out — do not edit.\nexport const ${camel}Abi = ${JSON.stringify(art.abi, null, 2)} as const;\n`);
  index.push(`export { ${camel}Abi } from "./${camel}.js";`);
}
writeFileSync(resolve(out, "index.ts"), index.join("\n") + "\n");
console.log(`wrote ${contracts.length} ABIs to ${out}`);
