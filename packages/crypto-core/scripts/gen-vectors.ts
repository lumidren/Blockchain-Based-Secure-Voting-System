/**
 * Generates Solidity test vectors (contracts/test/vectors/TestVectors.sol) from the TypeScript reference
 * implementation so the on-chain curve, Chaum–Pedersen and Lagrange code is checked against it.
 * Usage: pnpm --filter @verivote/crypto-core vectors
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { G, H, L, add, deriveH, mul, negate, randomScalar, type Point } from "../src/babyjub.js";
import * as cp from "../src/chaum-pedersen.js";
import { lagrangeCoefficients } from "../src/lagrange.js";

const outDir = resolve(dirname(fileURLToPath(import.meta.url)), "../../../contracts/test/vectors");
mkdirSync(outDir, { recursive: true });

const pt = (p: Point) => `P(${p.x}, ${p.y})`;

const adds = Array.from({ length: 8 }, () => {
  const p = mul(G, randomScalar());
  const q = mul(G, randomScalar());
  return { p, q, sum: add(p, q), dbl: add(p, p), neg: negate(p) };
});

const muls = Array.from({ length: 8 }, () => {
  const k = randomScalar();
  const p = mul(G, randomScalar());
  return { p, k, kp: mul(p, k) };
});
muls.push({ p: G, k: L - 1n, kp: negate(G) });
muls.push({ p: G, k: L, kp: { x: 0n, y: 1n } });
muls.push({ p: G, k: 1n, kp: G });

const mul2 = Array.from({ length: 6 }, () => {
  const k1 = randomScalar();
  const k2 = randomScalar();
  const p1 = mul(G, randomScalar());
  const p2 = mul(G, randomScalar());
  return { p1, k1, p2, k2, result: add(mul(p1, k1), mul(p2, k2)) };
});

const electionId = 4242n;
const cps = Array.from({ length: 4 }, (_, slot) => {
  const share = randomScalar();
  const s = mul(G, share);
  const c1 = mul(G, randomScalar());
  const { d, proof } = cp.prove(share, s, c1, electionId, slot);
  return { slot, s, c1, d, a: proof.a, b: proof.b, z: proof.z, e: cp.challenge(electionId, slot, s, c1, d, proof.a, proof.b) };
});

const lagr = [
  [1, 2, 3],
  [2, 4, 5],
  [1, 3, 5, 7],
  [3, 1, 2, 5, 4],
].map((idx) => ({ indices: idx, lambdas: lagrangeCoefficients(idx) }));

const h = deriveH();

const sol = `// SPDX-License-Identifier: MIT
pragma solidity 0.8.28;

// GENERATED by packages/crypto-core/scripts/gen-vectors.ts — do not edit by hand.
import {BabyJubJub} from "../../src/libraries/BabyJubJub.sol";

library TestVectors {
    struct AddVec { BabyJubJub.Point p; BabyJubJub.Point q; BabyJubJub.Point sum; BabyJubJub.Point dbl; BabyJubJub.Point neg; }
    struct MulVec { BabyJubJub.Point p; uint256 k; BabyJubJub.Point kp; }
    struct Mul2Vec { BabyJubJub.Point p1; uint256 k1; BabyJubJub.Point p2; uint256 k2; BabyJubJub.Point result; }
    struct CpVec { uint256 slot; BabyJubJub.Point s; BabyJubJub.Point c1; BabyJubJub.Point d; BabyJubJub.Point a; BabyJubJub.Point b; uint256 z; uint256 e; }
    struct LagrangeVec { uint256[] indices; uint256[] lambdas; }

    uint256 internal constant CP_ELECTION_ID = ${electionId};
    uint256 internal constant H_COUNTER = ${h.counter};

    function P(uint256 x, uint256 y) private pure returns (BabyJubJub.Point memory) { return BabyJubJub.Point(x, y); }

    function hPoint() internal pure returns (BabyJubJub.Point memory) { return ${pt(H)}; }

    function adds() internal pure returns (AddVec[] memory v) {
        v = new AddVec[](${adds.length});
${adds.map((a, i) => `        v[${i}] = AddVec(${pt(a.p)}, ${pt(a.q)}, ${pt(a.sum)}, ${pt(a.dbl)}, ${pt(a.neg)});`).join("\n")}
    }

    function muls() internal pure returns (MulVec[] memory v) {
        v = new MulVec[](${muls.length});
${muls.map((m, i) => `        v[${i}] = MulVec(${pt(m.p)}, ${m.k}, ${pt(m.kp)});`).join("\n")}
    }

    function mul2s() internal pure returns (Mul2Vec[] memory v) {
        v = new Mul2Vec[](${mul2.length});
${mul2.map((m, i) => `        v[${i}] = Mul2Vec(${pt(m.p1)}, ${m.k1}, ${pt(m.p2)}, ${m.k2}, ${pt(m.result)});`).join("\n")}
    }

    function cps() internal pure returns (CpVec[] memory v) {
        v = new CpVec[](${cps.length});
${cps.map((c, i) => `        v[${i}] = CpVec(${c.slot}, ${pt(c.s)}, ${pt(c.c1)}, ${pt(c.d)}, ${pt(c.a)}, ${pt(c.b)}, ${c.z}, ${c.e});`).join("\n")}
    }

    function lagranges() internal pure returns (LagrangeVec[] memory v) {
        v = new LagrangeVec[](${lagr.length});
${lagr
  .map((l, i) => {
    const idx = l.indices.map((n) => `        v[${i}].indices[${l.indices.indexOf(n)}] = ${n};`).join("\n");
    const lam = l.lambdas.map((n, j) => `        v[${i}].lambdas[${j}] = ${n};`).join("\n");
    return `        v[${i}].indices = new uint256[](${l.indices.length});\n        v[${i}].lambdas = new uint256[](${l.lambdas.length});\n${idx}\n${lam}`;
  })
  .join("\n")}
    }
}
`;
writeFileSync(resolve(outDir, "TestVectors.sol"), sol);
console.log(`vectors written to ${resolve(outDir, "TestVectors.sol")}`);
